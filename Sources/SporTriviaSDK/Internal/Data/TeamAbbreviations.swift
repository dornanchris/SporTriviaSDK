/// Consolidated team abbreviation dictionaries for all sports.
/// Maps team full name -> abbreviation code, and stat display name -> stat code.
enum TeamAbbreviations {

    /// Returns the abbreviation-to-name dictionary for the given sport.
    static func dictionary(for sport: Sport) -> [String: String] {
        switch sport {
        case .mlb: return baseball
        case .nba: return basketball
        case .nfl: return football
        case .nhl, .ahl, .echl: return hockey
        }
    }

    /// Reverse lookup: abbreviation -> full team/stat name.
    static func teamName(forAbbreviation abbr: String, sport: Sport) -> String? {
        let dict = dictionary(for: sport)
        for (key, val) in dict where val == abbr {
            return key
        }
        return nil
    }

